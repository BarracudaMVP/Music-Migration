export type TKey = keyof typeof translations.ru

export function t(key: TKey, lang: Lang): string {
  return translations[lang][key]
}

export function tStatus(status: string, lang: Lang): string {
  const map: Record<string, TKey> = {
    running: 'status_running',
    pending: 'status_pending',
    done: 'status_done',
    failed: 'status_failed',
    cancelled: 'status_cancelled',
  }
  const key = map[status]
  return key ? t(key, lang) : status
}

export function tService(id: string, lang: Lang): string {
  const map: Record<string, TKey> = {
    yandex_music: 'svc_yandex_music',
    spotify: 'svc_spotify',
    soundcloud: 'svc_soundcloud',
    file: 'svc_file',
  }
  const key = map[id]
  return key ? t(key, lang) : id
}

export function formatDate(iso: string | null, lang: Lang): string {
  if (!iso) return '—'
  const d = new Date(iso)
  const locale = lang === 'ru' ? 'ru-RU' : 'en-US'
  return d.toLocaleString(locale, {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}
